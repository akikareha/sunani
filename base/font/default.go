package font

import (
	"github.com/akikareha/sunani/api/canvas"
)

func DrawRune(x, y uint32, width, height uint32, r rune) {
	if r < 32 || r > 127 {
		return
	}
	drawGlyph(x, y, width, height, glyphs[r-32])
}

const (
	gridWidth  = 8
	gridHeight = 16
)

func drawGlyph(x, y uint32, width, height uint32, glyph []uint8) {
	if len(glyph) < 1 {
		return
	}
	i := 0
	polylines := int(glyph[i])
	i++
	for k := 0; k < polylines; k++ {
		if i >= len(glyph) {
			return
		}
		segments := int(glyph[i])
		i++
		if segments < 1 {
			continue
		}
		if i+1 >= len(glyph) {
			return
		}
		x1 := uint32(glyph[i])
		i++
		y1 := uint32(glyph[i])
		i++
		for j := 1; j < segments; j++ {
			if i+1 >= len(glyph) {
				return
			}
			x2 := uint32(glyph[i])
			i++
			y2 := uint32(glyph[i])
			i++
			canvas.Line(
				x+x1*width/gridWidth,
				y+y1*height/gridHeight,
				x+x2*width/gridWidth,
				y+y2*height/gridHeight,
			)
			x1 = x2
			y1 = y2
		}
	}
}

