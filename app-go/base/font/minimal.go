package font

import (
	"github.com/akikareha/sunani/app-go/api/canvas"
)

func DrawMinimalRune(x, y int32, width, height int32, r rune) {
	if r < 32 || r > 127 {
		return
	}
	drawMinimalGlyph(x, y, width, height, minimalGlyphs[r-32])
}

const (
	minimalGridWidth  = 4
	minimalGridHeight = 8
)

func drawMinimalGlyph(x, y int32, width, height int32, glyph []uint8) {
	if len(glyph) < 1 {
		return
	}
	i := 0
	polylines := int(glyph[i])
	i++
	for k := 0; k < polylines; k++ {
		if i >= len(glyph) {
			return
		}
		segments := int(glyph[i])
		i++
		if segments < 1 {
			continue
		}
		if i+1 >= len(glyph) {
			return
		}
		x1 := int32(glyph[i])
		i++
		y1 := int32(glyph[i])
		i++
		for j := 1; j < segments; j++ {
			if i+1 >= len(glyph) {
				return
			}
			x2 := int32(glyph[i])
			i++
			y2 := int32(glyph[i])
			i++
			canvas.Line(
				x+x1*width/minimalGridWidth,
				y+y1*height/minimalGridHeight,
				x+x2*width/minimalGridWidth,
				y+y2*height/minimalGridHeight,
			)
			x1 = x2
			y1 = y2
		}
	}
}

